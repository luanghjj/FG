<div class="note">⚠️ <b>HỌC THUỘC:</b> Pseudo-Getreide werden <b>wie Reis</b> in Wasser/Brühe im <b>Verhältnis 1 : 2</b> gegart. Vorheriges Anrösten hebt den nussigen Geschmack hervor. → Giả ngũ cốc nấu như gạo, tỉ lệ 1 : 2 (1 hạt : 2 nước); rang sơ trước làm nổi vị bùi hạt dẻ.</div>

